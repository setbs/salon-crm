export type CrmTextKey = keyof typeof crmText.en;

export function crmLabel(language: CrmLanguage, key: CrmTextKey) {
  return crmText[language][key];
}

export function readStoredCrmLanguage(): CrmLanguage {
  if (typeof window === "undefined") {
    return "uk";
  }

  return window.localStorage.getItem(CRM_LANGUAGE_STORAGE_KEY) === "en" ? "en" : "uk";
}

export function storeCrmLanguage(language: CrmLanguage) {
  if (typeof window === "undefined") {
    return;
  }

  window.localStorage.setItem(CRM_LANGUAGE_STORAGE_KEY, language);
}

export const CrmLanguageContext = createContext<CrmLanguage>("uk");

export function useCrmLanguage() {
  return useContext(CrmLanguageContext);
}

export function useCrmT() {
  const language = useCrmLanguage();

  return (key: CrmTextKey) => crmLabel(language, key);
}
